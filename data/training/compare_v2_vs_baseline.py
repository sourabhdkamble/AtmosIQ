import json
import sys
from pathlib import Path

DATA_DIR = Path(__file__).resolve().parent
BASELINE_FILE = DATA_DIR / "challenge_eval_25_baseline_predictions.json"
V2_REPORT_FILE = DATA_DIR / "atmosiq_lora_v2_challenge_report.json"
CHALLENGE_FILE = DATA_DIR / "challenge_eval_25.json"

def main():
    if not BASELINE_FILE.exists():
        print(f"Error: Baseline predictions file not found at {BASELINE_FILE}")
        sys.exit(1)

    with open(BASELINE_FILE, "r", encoding="utf-8") as f:
        baseline_data = json.load(f)

    baseline_total = baseline_data["total_prompts"]
    baseline_correct = baseline_data["correct_predictions"]
    baseline_acc = baseline_data["accuracy"]

    print("\n" + "=" * 80)
    print(" AtmosIQ Evaluation: Keyword Baseline vs LoRA V2 Adapter on 25 Challenge Prompts")
    print("=" * 80)
    print(f"Dataset: 25 Challenge Prompts ({CHALLENGE_FILE.name})")
    print(f"Keyword Routing Baseline Accuracy: {baseline_correct}/{baseline_total} ({baseline_acc:.2%})\n")

    if not V2_REPORT_FILE.exists():
        print(f"[STATUS] LoRA V2 report '{V2_REPORT_FILE.name}' is NOT yet on disk.")
        print("Reason: Google Colab T4 evaluation run must be executed to produce verified model predictions.")
        print("\nBaseline Failure Analysis on the 25 Challenge Prompts:")
        print("-" * 80)
        failures = [r for r in baseline_data["results"] if not r["correct"]]
        for idx, f_item in enumerate(failures, 1):
            print(f"  {idx:02d}. [ID {f_item['id']:02d}] '{f_item['text']}'")
            print(f"      Expected: {f_item['expected']} | Baseline Predicted: {f_item['predicted']} (Fell back to knowledge)")
        print("-" * 80)
        print(f"Total Keyword Failures: {len(failures)}/25 (All due to rigid keyword matching)")
        print("\nRun the Colab notebook 'AtmosIQ_LoRA_V2_Challenge_Evaluation.ipynb' or execute")
        print("evaluate_adapter_inference.py with GPU to populate atmosiq_lora_v2_challenge_report.json.")
        print("=" * 80)
        return

    with open(V2_REPORT_FILE, "r", encoding="utf-8") as f:
        v2_data = json.load(f)

    v2_total = v2_data["total_prompts"]
    v2_correct = v2_data["correct_predictions"]
    v2_acc = v2_data["accuracy"]
    v2_invalid = v2_data.get("invalid_route_count", 0)

    delta_pct = (v2_acc - baseline_acc) * 100
    print(f"LoRA V2 Accuracy: {v2_correct}/{v2_total} ({v2_acc:.2%})")
    print(f"Absolute Difference: {delta_pct:+.2f} percentage points ({'improvement' if delta_pct > 0 else 'drop' if delta_pct < 0 else 'identical'})")
    print(f"Invalid Routes Generated by V2: {v2_invalid}\n")

    print(f"{'ID':<4} {'Expected':<16} {'Baseline':<16} {'LoRA V2':<16} {'Prompt':<30}")
    print("-" * 85)
    
    b_map = {r["id"]: r for r in baseline_data["results"]}
    v_map = {r["id"]: r for r in v2_data["predictions"]}

    v2_errors = []
    for item_id in sorted(b_map.keys()):
        b = b_map[item_id]
        v = v_map.get(item_id, {})
        b_mark = "✓" if b["correct"] else "✗"
        v_mark = "✓" if v.get("correct") else "✗"
        v_pred = v.get("predicted", "N/A")
        print(f"{item_id:02d}   {b['expected']:<16} {b['predicted'] + ' ' + b_mark:<16} {str(v_pred) + ' ' + v_mark:<16} {b['text'][:30]}...")
        if not v.get("correct"):
            v2_errors.append(v)

    print("-" * 85)
    print("\n=== Per-Class Performance Comparison ===")
    v2_per_class = v2_data.get("per_class_metrics", {})
    if v2_per_class:
        print(f"{'Route':<18} {'Precision':<12} {'Recall':<12} {'F1-Score':<12} {'Support':<8}")
        print("-" * 65)
        for route, metrics in sorted(v2_per_class.items()):
            print(f"{route:<18} {metrics['precision']:<12.4f} {metrics['recall']:<12.4f} {metrics['f1-score']:<12.4f} {metrics['support']:<8}")
        macro = v2_data.get("macro_avg", {})
        if macro:
            print("-" * 65)
            print(f"{'Macro Average':<18} {macro['precision']:<12.4f} {macro['recall']:<12.4f} {macro['f1-score']:<12.4f} {macro['support']:<8}")

    print("\n=== Confusion Matrix ===")
    cm = v2_data.get("confusion_matrix", {})
    if cm:
        routes = sorted(cm.keys())
        header = f"{'Actual \\ Pred':<16} " + " ".join(f"{r[:8]:>8}" for r in routes)
        print(header)
        print("-" * len(header))
        for act in routes:
            row = f"{act:<16} " + " ".join(f"{cm[act].get(p, 0):>8}" for p in routes)
            print(row)

    print("\n=== Misclassified Prompts by LoRA V2 ===")
    if not v2_errors:
        print("None! 100% of challenge prompts correctly classified.")
    else:
        for err in v2_errors:
            print(f"- [ID {err.get('id')}] '{err.get('text')}'")
            print(f"  Expected: {err.get('expected')} | Predicted: {err.get('predicted')} | Raw: '{err.get('raw_output')}'")

    print("=" * 85)

if __name__ == "__main__":
    main()
